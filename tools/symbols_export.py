#!/usr/bin/env python3
"""Turn index/symbols.tsv into a script that names FastView.exe in a
disassembler.

  python3 -I tools/symbols_export.py ghidra [index/symbols.tsv] > fastview_symbols.py
  python3 -I tools/symbols_export.py idc    [index/symbols.tsv] > fastview_symbols.idc
  python3 -I tools/symbols_export.py r2     [index/symbols.tsv] > fastview_symbols.r2

ghidra: a Ghidra script (Jython or PyGhidra) — run it from the Script
        Manager with FastView.exe open: creates a function at every `func`
        address that has none and labels every address (primary label).
idc:    an IDA script — File ▸ Script file.
r2:     rizin / radare2 commands — `. fastview_symbols.r2` (flags; `af` +
        `afn` for functions).
Every name is prefixed `fv_` only where the tool forbids its first
character; the names are ours (index/names.tsv) or derived from the
message maps, vtables and imports (tools/index.py).
"""
import sys

fmt = sys.argv[1] if len(sys.argv) > 1 else ""
path = sys.argv[2] if len(sys.argv) > 2 else "index/symbols.tsv"
rows = []
for line in open(path, encoding="utf-8").read().splitlines()[1:]:
    if line.strip():
        addr, kind, name, _src = line.split("\t")
        rows.append((int(addr, 16), kind, name))

if fmt == "ghidra":
    print("# Names FastView.exe from index/symbols.tsv (generated by tools/symbols_export.py).")
    print("# @category FastView")
    print("from ghidra.program.model.symbol import SourceType")
    print("ROWS = [")
    for a, k, n in rows:
        print(f"    ({a:#x}, {k!r}, {n!r}),")
    print("]")
    print("for a, kind, name in ROWS:")
    print("    addr = toAddr(a)")
    print("    if kind == 'func' and getFunctionAt(addr) is None:")
    print("        createFunction(addr, name)")
    print("    createLabel(addr, name, True, SourceType.USER_DEFINED)")
    print("print('FastView: %d names' % len(ROWS))")
elif fmt == "idc":
    print("// Names FastView.exe from index/symbols.tsv (generated by tools/symbols_export.py).")
    print("#include <idc.idc>")
    print("static main() {")
    for a, k, n in rows:
        if k == "func":
            print(f"  add_func({a:#x}, BADADDR);")
        print(f'  set_name({a:#x}, "{n}", SN_NOWARN | SN_NOCHECK);')
    print("}")
elif fmt == "r2":
    print("# Names FastView.exe from index/symbols.tsv (generated by tools/symbols_export.py).")
    for a, k, n in rows:
        if k == "func":
            print(f"af @ {a:#x}")
            print(f"afn {n} @ {a:#x}")
        print(f"f fv.{n} @ {a:#x}")
else:
    sys.exit(__doc__)
